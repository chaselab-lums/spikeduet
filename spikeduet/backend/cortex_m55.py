"""Cortex-M55 backend (journal extension N2): the portable-C schedule with per-layer affine realizations
for the M55's scalar core and its Helium (MVE) vector unit.

Realizations of one `AffineOp` (chosen per layer by the caller; N5 will choose them from a cost model):

  * "scalar_dense"  -- the shared portable-C scalar loop (row-major weights from model_data.h).
  * "scalar_event"  -- scan the input for nonzeros once, then per output row add only the active columns.
  * "helium_dense"  -- MVE over 4 output rows per vector (16 rows per register block), transposed weights.
  * "helium_event"  -- the same over the active columns only (vectorized column gather/accumulate).

Every realization is BIT-EXACT to "scalar_dense" (which is the portable-C kernel): each output keeps the
scalar order  c = bias;  c = c + w[i] * x[i]  for i ascending, as a separate multiply and add. The vector
kernels put four OUTPUT ROWS in the lanes (never four input columns), so no lane ever reorders a sum; the
event kernels skip only exact zeros, whose products add a signed zero. Fused multiply-add would round
once instead of twice, so builds must use -ffp-contract=off and the kernels never call vfmaq.
When every active input is exactly 1.0 (binary spikes) the event kernels add the weight directly, which
is the same value as w * 1.0f.

On a host without MVE, m55_kernels.h defines the five MVE intrinsics it uses as plain lane-wise C (same
IEEE single-precision results), so the generated runtime host-compiles for parity tests. On the M55
(`__ARM_FEATURE_MVE & 2`) the real `arm_mve.h` is used. MVE single-precision honours FPSCR like the scalar
FPU; with the reset FPSCR (round to nearest, no flush-to-zero) results match the host.

Weights: model_data.h is rendered with exact float literals (lossless). Helium layers additionally get a
transposed, 4-row-padded table [in][out_pad] in m55_weights.h. Every weight array carries the macro
ISCAS_M55_WSECT (empty by default) so an N6 build can place weights in a linker section (SRAM or XIP).
"""
import re
from typing import Dict, Optional, Union

import numpy as np

from spikeduet.backend.base import Backend, GeneratedArtifact
from spikeduet.backend.c_common import array_literal, layer_sequence, render_model_data_header
from spikeduet.backend.portable_c import _MODEL_DATA_GUARD, _generate_runtime_c, _model_config_header, _runtime_h
from spikeduet.backend.schedule_common import buffer_ref, scalar_affine_emitter
from spikeduet.ir.execution import AffineOp, ExecutionModule
from spikeduet.ir.execution_verifier import verify_execution_ir

REALIZATIONS = ("scalar_dense", "scalar_event", "helium_dense", "helium_event")
M55_CFLAGS = ("-mcpu=cortex-m55", "-mthumb", "-mfloat-abi=hard", "-O2", "-ffp-contract=off", "-std=c99")

M55_KERNELS_H = r"""/* Generated by SpikeDuet -- fixed text, do not edit by hand.
 * Cortex-M55 affine kernels. Every kernel keeps, per output row, the scalar order
 *   c = bias;  c = c + w[i] * x[i]  (i ascending, separate multiply and add)
 * so all of them are bit-exact to the portable scalar loop. Build with -ffp-contract=off. */
#ifndef ISCAS_M55_KERNELS_H
#define ISCAS_M55_KERNELS_H
#include <stdint.h>
#include <string.h>

#if defined(__ARM_FEATURE_MVE) && (__ARM_FEATURE_MVE & 2)
#include <arm_mve.h>
#define ISCAS_M55_HAVE_MVE 1
#else
/* Host stand-in for the five MVE intrinsics used below: lane-wise IEEE single precision. */
#define ISCAS_M55_HAVE_MVE 0
typedef struct { float v[4]; } float32x4_t;
static inline float32x4_t vld1q_f32(const float *p) { float32x4_t r; memcpy(r.v, p, sizeof r.v); return r; }
static inline void vst1q_f32(float *p, float32x4_t a) { memcpy(p, a.v, sizeof a.v); }
static inline float32x4_t vdupq_n_f32(float s) { float32x4_t r; for (int k = 0; k < 4; k++) r.v[k] = s; return r; }
static inline float32x4_t vaddq_f32(float32x4_t a, float32x4_t b) { for (int k = 0; k < 4; k++) a.v[k] = a.v[k] + b.v[k]; return a; }
static inline float32x4_t vmulq_f32(float32x4_t a, float32x4_t b) { for (int k = 0; k < 4; k++) a.v[k] = a.v[k] * b.v[k]; return a; }
#endif

#if defined(__GNUC__)
#define ISCAS_M55_KERNEL __attribute__((noinline, unused))
#else
#define ISCAS_M55_KERNEL
#endif

/* Indices of the nonzero inputs (ascending); returns their count, *all_one = every one of them is 1.0f. */
static inline int iscas_m55_scan(const float *x, int n_in, uint16_t *idx, int *all_one)
{
    int n = 0, one = 1;
    for (int i = 0; i < n_in; i++) {
        const float v = x[i];
        if (v != 0.0f) {
            idx[n++] = (uint16_t)i;
            one &= (v == 1.0f);
        }
    }
    *all_one = one;
    return n;
}

/* Last partial block: compute four lanes, keep the valid ones. */
static inline void iscas_m55_store_tail(float *out, float32x4_t acc, int valid)
{
    float tmp[4];
    vst1q_f32(tmp, acc);
    for (int k = 0; k < valid; k++) out[k] = tmp[k];
}

/* Helium dense: wt[i * out_pad + r] = W[r][i], bias padded to out_pad. */
ISCAS_M55_KERNEL static void iscas_m55_helium_dense(const float *wt, const float *bias, const float *x,
                                                    float *out, int n_in, int n_out, int out_pad)
{
    int r = 0;
    for (; r + 16 <= n_out; r += 16) {
        float32x4_t a0 = vld1q_f32(bias + r), a1 = vld1q_f32(bias + r + 4);
        float32x4_t a2 = vld1q_f32(bias + r + 8), a3 = vld1q_f32(bias + r + 12);
        const float *w = wt + r;
        for (int i = 0; i < n_in; i++, w += out_pad) {
            const float32x4_t xv = vdupq_n_f32(x[i]);
            a0 = vaddq_f32(a0, vmulq_f32(vld1q_f32(w), xv));
            a1 = vaddq_f32(a1, vmulq_f32(vld1q_f32(w + 4), xv));
            a2 = vaddq_f32(a2, vmulq_f32(vld1q_f32(w + 8), xv));
            a3 = vaddq_f32(a3, vmulq_f32(vld1q_f32(w + 12), xv));
        }
        vst1q_f32(out + r, a0); vst1q_f32(out + r + 4, a1); vst1q_f32(out + r + 8, a2); vst1q_f32(out + r + 12, a3);
    }
    for (; r < n_out; r += 4) {
        float32x4_t a = vld1q_f32(bias + r);
        const float *w = wt + r;
        for (int i = 0; i < n_in; i++, w += out_pad) a = vaddq_f32(a, vmulq_f32(vld1q_f32(w), vdupq_n_f32(x[i])));
        if (r + 4 <= n_out) vst1q_f32(out + r, a); else iscas_m55_store_tail(out + r, a, n_out - r);
    }
}

/* Helium event-driven: the same, over the n active columns idx[0..n) only. */
ISCAS_M55_KERNEL static void iscas_m55_helium_event(const float *wt, const float *bias, const float *x,
                                                    float *out, int n_out, int out_pad,
                                                    const uint16_t *idx, int n, int all_one)
{
    int r = 0;
    for (; r + 16 <= n_out; r += 16) {
        float32x4_t a0 = vld1q_f32(bias + r), a1 = vld1q_f32(bias + r + 4);
        float32x4_t a2 = vld1q_f32(bias + r + 8), a3 = vld1q_f32(bias + r + 12);
        if (all_one) {
            for (int k = 0; k < n; k++) {
                const float *w = wt + (int)idx[k] * out_pad + r;
                a0 = vaddq_f32(a0, vld1q_f32(w));     a1 = vaddq_f32(a1, vld1q_f32(w + 4));
                a2 = vaddq_f32(a2, vld1q_f32(w + 8)); a3 = vaddq_f32(a3, vld1q_f32(w + 12));
            }
        } else {
            for (int k = 0; k < n; k++) {
                const float *w = wt + (int)idx[k] * out_pad + r;
                const float32x4_t xv = vdupq_n_f32(x[idx[k]]);
                a0 = vaddq_f32(a0, vmulq_f32(vld1q_f32(w), xv));
                a1 = vaddq_f32(a1, vmulq_f32(vld1q_f32(w + 4), xv));
                a2 = vaddq_f32(a2, vmulq_f32(vld1q_f32(w + 8), xv));
                a3 = vaddq_f32(a3, vmulq_f32(vld1q_f32(w + 12), xv));
            }
        }
        vst1q_f32(out + r, a0); vst1q_f32(out + r + 4, a1); vst1q_f32(out + r + 8, a2); vst1q_f32(out + r + 12, a3);
    }
    for (; r < n_out; r += 4) {
        float32x4_t a = vld1q_f32(bias + r);
        for (int k = 0; k < n; k++) {
            const float32x4_t w = vld1q_f32(wt + (int)idx[k] * out_pad + r);
            a = all_one ? vaddq_f32(a, w) : vaddq_f32(a, vmulq_f32(w, vdupq_n_f32(x[idx[k]])));
        }
        if (r + 4 <= n_out) vst1q_f32(out + r, a); else iscas_m55_store_tail(out + r, a, n_out - r);
    }
}

/* Scalar event-driven, row-major W[r * n_in + i] (the model_data.h layout). */
ISCAS_M55_KERNEL static void iscas_m55_scalar_event(const float *w, const float *bias, const float *x,
                                                    float *out, int n_in, int n_out,
                                                    const uint16_t *idx, int n, int all_one)
{
    for (int r = 0; r < n_out; r++) {
        const float *row = w + (size_t)r * n_in;
        float c = bias ? bias[r] : 0.0f;
        if (all_one) {
            for (int k = 0; k < n; k++) c = c + row[idx[k]];
        } else {
            for (int k = 0; k < n; k++) c = c + row[idx[k]] * x[idx[k]];
        }
        out[r] = c;
    }
}
#endif
"""


def _pad4(n: int) -> int:
    return (n + 3) // 4 * 4


def _sectioned_model_data(text: str) -> str:
    text = re.sub(r"(static const float iscas_layer\d+_weight\[\d+\])", r"\1 ISCAS_M55_WSECT", text)
    guard = "#ifndef ISCAS_M55_WSECT\n#define ISCAS_M55_WSECT\n#endif\n"
    first = text.index("#define")              # after the include guard's #define
    eol = text.index("\n", first) + 1
    return text[:eol] + guard + text[eol:]


class CortexM55Backend(Backend):
    """Portable schedule + per-layer M55 affine realizations (see the module docstring)."""

    name = "cortex_m55"

    def generate(self, module: ExecutionModule, *, realization: Union[str, Dict[int, str]] = "helium_dense",
                 include_harness: bool = False) -> GeneratedArtifact:
        verify_execution_ir(module)
        linears, _ = layer_sequence(module)
        n = len(linears)
        if isinstance(realization, str):
            choice = {l: realization for l in range(n)}
        else:
            choice = {l: realization.get(l, "scalar_dense") for l in range(n)}
        for l, r in choice.items():
            if r not in REALIZATIONS:
                raise ValueError(f"layer {l}: unknown realization {r!r} (choose from {REALIZATIONS})")
            if r != "scalar_dense" and linears[l].synapse_delays is not None:
                raise ValueError(f"layer {l}: per-synapse delays are only supported by 'scalar_dense'")
        max_w = max([l.in_features for l in linears] + [l.out_features for l in linears])

        tables = ["/* Generated by SpikeDuet -- do not edit by hand */",
                  "#ifndef ISCAS_M55_WEIGHTS_H", "#define ISCAS_M55_WEIGHTS_H",
                  "#ifndef ISCAS_M55_WSECT", "#define ISCAS_M55_WSECT", "#endif"]
        for l, lin in enumerate(linears):
            if not choice[l].startswith("helium"):
                continue
            out_pad = _pad4(lin.out_features)
            w = lin.weight.detach().cpu().numpy().astype(np.float32)          # [out, in]
            wt = np.zeros((lin.in_features, out_pad), np.float32)
            wt[:, :lin.out_features] = w.T
            b = np.zeros(out_pad, np.float32)
            if lin.bias is not None:
                b[:lin.out_features] = lin.bias.detach().cpu().numpy().astype(np.float32)
            tables.append(f"static const float ISCAS_M55_WT{l}[{wt.size}] ISCAS_M55_WSECT = {array_literal(wt.ravel().tolist(), True)};")
            tables.append(f"static const float ISCAS_M55_B{l}[{out_pad}] = {array_literal(b.tolist(), True)};")
        tables += ["#endif", ""]

        def emitter(op: AffineOp, idx: int):
            r = choice[idx]
            if r == "scalar_dense":
                return scalar_affine_emitter(op, idx)
            lin = op.weight_layer
            x = buffer_ref(op.input)
            n_in, n_out, out_pad = lin.in_features, lin.out_features, _pad4(lin.out_features)
            if r == "helium_dense":
                call = [f"        iscas_m55_helium_dense(ISCAS_M55_WT{idx}, ISCAS_M55_B{idx}, {x}, g_current[{idx}], "
                        f"{n_in}, {n_out}, {out_pad});"]
            else:
                scan = f"        int all_one; const int n = iscas_m55_scan({x}, {n_in}, g_m55_idx, &all_one);"
                if r == "helium_event":
                    call = [scan, f"        iscas_m55_helium_event(ISCAS_M55_WT{idx}, ISCAS_M55_B{idx}, {x}, g_current[{idx}], "
                                  f"{n_out}, {out_pad}, g_m55_idx, n, all_one);"]
                else:
                    call = [scan, f"        iscas_m55_scalar_event(ISCAS_LAYERS[{idx}].weight, ISCAS_LAYERS[{idx}].bias, {x}, "
                                  f"g_current[{idx}], {n_in}, {n_out}, g_m55_idx, n, all_one);"]
            return [f"    {{ /* {op.id}: affine layer {idx} ({r}) */", *call,
                    f"        g_affine_exec_count[{idx}]++;", "    }"]

        runtime = _generate_runtime_c(module, affine_emitter=emitter, generator="cortex_m55.py",
                                      extra_includes=['#include "m55_kernels.h"', '#include "m55_weights.h"'],
                                      extra_storage=[f"static uint16_t g_m55_idx[{max_w}];   /* active input indices */"]
                                      if any(r.endswith("_event") for r in choice.values()) else [])
        files = {
            "model_data.h": _sectioned_model_data(render_model_data_header(module, guard=_MODEL_DATA_GUARD, exact_floats=True)),
            "model_config.h": _model_config_header(module, max_w),
            "portable_runtime.h": _runtime_h(module),
            "m55_kernels.h": M55_KERNELS_H,
            "m55_weights.h": "\n".join(tables),
            "m55_runtime.c": runtime,
            "m55_realization.txt": "\n".join(f"layer {l}: {choice[l]}" for l in range(n)) + "\n",
        }
        if include_harness:
            from spikeduet.backend.portable_c import _HARNESS_C
            files["main.c"] = _HARNESS_C
        return GeneratedArtifact(files=files)
