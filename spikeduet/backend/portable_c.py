"""Portable-C backend: plain C99 with no vendor dependency.

Generates ``model_data.h`` (shared descriptor table), ``model_config.h`` (timestep count, input
mode, largest layer width), ``portable_runtime.h`` (fixed LIF helpers and the public API) and a
per-model ``portable_runtime.c`` that executes the module's schedule literally: preheader ops once,
loop-body ops on every step. Buffers are static arrays; nothing is allocated at runtime.
``include_harness=True`` adds a host ``main.c`` that reads samples from stdin.
"""

from spikeduet.backend.base import Backend, GeneratedArtifact
from spikeduet.backend.c_common import layer_sequence, render_model_data_header
from spikeduet.backend.schedule_common import emit_schedule, scalar_affine_emitter
from spikeduet.ir.execution import ExecutionModule, TemporalMode
from spikeduet.ir.execution_verifier import verify_execution_ir

_MODEL_DATA_GUARD = "ISCAS_PORTABLE_MODEL_DATA_H"
_CONFIG_GUARD = "ISCAS_PORTABLE_MODEL_CONFIG_H"


def _model_config_header(module: ExecutionModule, max_layer_width: int) -> str:
    input_mode = module.get_buffer(module.input_buffer).temporal
    input_temporal_flag = 1 if input_mode is TemporalMode.VARYING else 0

    return "\n".join(
        [
            "// Generated by SpikeDuet -- do not edit by hand",
            f"#ifndef {_CONFIG_GUARD}",
            f"#define {_CONFIG_GUARD}",
            "",
            f"#define ISCAS_STEPS {module.num_timesteps}",
            "/* 0: one [ISCAS_INPUT_DIM] vector is reused on every timestep.",
            "   1: the caller passes [ISCAS_STEPS][ISCAS_INPUT_DIM], one vector per timestep. */",
            f"#define ISCAS_INPUT_TEMPORAL {input_temporal_flag}",
            "/* Largest in_features/out_features; sizes every static per-layer array. */",
            f"#define ISCAS_MAX_LAYER_WIDTH {max_layer_width}",
            "",
            f"#endif // {_CONFIG_GUARD}",
            "",
        ]
    )


# Same text for every model. The helpers mirror runtime/efr32/snn.h, copied rather than included so
# this backend does not depend on the firmware tree.
_RUNTIME_H = """// Generated by SpikeDuet -- do not edit by hand
#ifndef ISCAS_PORTABLE_RUNTIME_H
#define ISCAS_PORTABLE_RUNTIME_H

#include <math.h>

#include "model_data.h"
#include "model_config.h"

static inline float iscas_param_at(const float *arr, int len, int j) {
    return (len == 1) ? arr[0] : arr[j];
}

static inline float iscas_state_quantize(float x, const float *levels, int n_levels) {
    float best = levels[0];
    float best_diff = fabsf(levels[0] - x);
    for (int i = 1; i < n_levels; i++) {
        float diff = fabsf(levels[i] - x);
        if (diff < best_diff) {
            best_diff = diff;
            best = levels[i];
        }
    }
    return best;
}

static inline void iscas_lif_update(
    float current, float old_mem, float beta, float threshold,
    int reset_mechanism, int reset_delay, float graded_spikes_factor,
    const float *state_quant_levels, int state_quant_num_levels,
    float *out_spike, float *out_new_mem)
{
    float reset_old = (old_mem > threshold) ? 1.0f : 0.0f;
    float spike, new_mem;

    if (reset_mechanism == 0) {           /* subtract */
        if (!reset_delay) {
            float updated = (beta * old_mem) + current - reset_old * threshold;
            if (state_quant_num_levels > 0) {
                updated = iscas_state_quantize(updated, state_quant_levels, state_quant_num_levels);
            }
            spike = (updated > threshold) ? 1.0f : 0.0f;
            float do_reset = spike - reset_old;
            new_mem = updated - do_reset * threshold;
        } else {
            new_mem = (beta * old_mem) + current - reset_old * threshold;
            if (state_quant_num_levels > 0) {
                new_mem = iscas_state_quantize(new_mem, state_quant_levels, state_quant_num_levels);
            }
            spike = (new_mem > threshold) ? 1.0f : 0.0f;
        }
    } else if (reset_mechanism == 1) {    /* zero */
        float zeroed = (1.0f - reset_old) * old_mem;
        if (!reset_delay) {
            float updated = (beta * zeroed) + current;
            if (state_quant_num_levels > 0) {
                updated = iscas_state_quantize(updated, state_quant_levels, state_quant_num_levels);
            }
            spike = (updated > threshold) ? 1.0f : 0.0f;
            float do_reset = spike - reset_old;
            new_mem = (1.0f - do_reset) * updated;
        } else {
            new_mem = (beta * zeroed) + current;
            if (state_quant_num_levels > 0) {
                new_mem = iscas_state_quantize(new_mem, state_quant_levels, state_quant_num_levels);
            }
            spike = (new_mem > threshold) ? 1.0f : 0.0f;
        }
    } else {                               /* none (2) */
        new_mem = (beta * old_mem) + current;
        if (state_quant_num_levels > 0) {
            new_mem = iscas_state_quantize(new_mem, state_quant_levels, state_quant_num_levels);
        }
        spike = (new_mem > threshold) ? 1.0f : 0.0f;
    }

    *out_spike = spike * graded_spikes_factor;
    *out_new_mem = new_mem;
}

static inline void iscas_lif_update_inhibition_layer(
    const iscas_layer_t *L, const float *current, float *mem,
    float *mem_state_scratch, float *reset_old_scratch, float *out_spike)
{
    int n = L->out_features;
    int winner = 0;
    float best_margin = 0.0f;

    for (int j = 0; j < n; j++) {
        float beta = iscas_param_at(L->beta, L->beta_len, j);
        float threshold = iscas_param_at(L->threshold, L->threshold_len, j);
        float old_mem = mem[j];
        float reset_old = (old_mem > threshold) ? 1.0f : 0.0f;
        float mem_state;

        if (L->reset_mechanism == 0) {
            mem_state = (beta * old_mem) + current[j] - reset_old * threshold;
        } else if (L->reset_mechanism == 1) {
            float zeroed = (1.0f - reset_old) * old_mem;
            mem_state = (beta * zeroed) + current[j];
        } else {
            mem_state = (beta * old_mem) + current[j];
        }

        if (L->state_quant_num_levels > 0) {
            mem_state = iscas_state_quantize(mem_state, L->state_quant_levels, L->state_quant_num_levels);
        }

        mem_state_scratch[j] = mem_state;
        reset_old_scratch[j] = reset_old;

        float margin = mem_state - threshold;
        if (j == 0 || margin > best_margin) {
            best_margin = margin;
            winner = j;
        }
    }

    for (int j = 0; j < n; j++) {
        float threshold = iscas_param_at(L->threshold, L->threshold_len, j);
        float mem_state = mem_state_scratch[j];
        float reset_old = reset_old_scratch[j];
        float margin = mem_state - threshold;
        float fired = (margin > 0.0f) ? 1.0f : 0.0f;
        float spike = (j == winner) ? fired : 0.0f;
        float new_mem = mem_state;

        if (!L->reset_delay && (L->reset_mechanism == 0 || L->reset_mechanism == 1)) {
            float graded_factor = iscas_param_at(L->graded_spikes_factor, L->graded_spikes_factor_len, j);
            float do_reset = (spike / graded_factor) - reset_old;
            if (L->reset_mechanism == 0) {
                new_mem = mem_state - do_reset * threshold;
            } else {
                new_mem = mem_state - do_reset * mem_state;
            }
        }

        mem[j] = new_mem;
        out_spike[j] = spike;
    }
}

void iscas_model_init(void);

/* Runs one inference and returns the predicted class.
 *
 * input: [ISCAS_INPUT_DIM] if ISCAS_INPUT_TEMPORAL == 0 (reused on every step), otherwise
 * [ISCAS_STEPS][ISCAS_INPUT_DIM] row-major. Membranes are reset at the start of every call.
 * Readout: the final layer's membrane summed over all steps, then argmax.
 */
int iscas_model_run(const float *input);

#ifdef ISCAS_PORTABLE_EXPOSE_MEMSUM
/* Final-layer membrane sums (the argmax input) of the last iscas_model_run() call. */
const float *iscas_model_last_mem_sum(int *out_dim);
#endif

/* How many times each layer's affine, LIF and staging copy ran during the last call. Used by the
 * tests to check the schedule (e.g. a hoisted affine runs once, a fused copy never runs). */
int iscas_model_debug_affine_exec_count(int layer);
int iscas_model_debug_lif_exec_count(int layer);
int iscas_model_debug_convert_exec_count(int layer);

#endif /* ISCAS_PORTABLE_RUNTIME_H */
"""


def _generate_runtime_c(module: ExecutionModule) -> str:
    """Per-model ``portable_runtime.c``: storage, ``iscas_model_init()`` and ``iscas_model_run()``."""
    preheader_lines, loop_lines = emit_schedule(
        module, affine_emitter=scalar_affine_emitter, input_param="input"
    )

    lines = [
        "// Generated by SpikeDuet -- do not edit by hand",
        "/* Portable C99 runtime. The preheader block runs once per iscas_model_run() call and the loop",
        " * block ISCAS_STEPS times, exactly as the Execution IR this file was generated from specifies.",
        " * LIF semantics live in portable_runtime.h. */",
        "#include <string.h>",
        "",
        "#include \"portable_runtime.h\"",
        "",
        "static float g_mem[ISCAS_NUM_LAYERS][ISCAS_MAX_LAYER_WIDTH];",
        "static float g_stage[ISCAS_NUM_LAYERS][ISCAS_MAX_LAYER_WIDTH];    /* ConvertOp output */",
        "static float g_current[ISCAS_NUM_LAYERS][ISCAS_MAX_LAYER_WIDTH];",
        "static float g_spike[ISCAS_NUM_LAYERS][ISCAS_MAX_LAYER_WIDTH];",
        "static float g_inhib_mem_state[ISCAS_NUM_LAYERS][ISCAS_MAX_LAYER_WIDTH];",
        "static float g_inhib_reset_old[ISCAS_NUM_LAYERS][ISCAS_MAX_LAYER_WIDTH];",
        "static float g_mem_sum[ISCAS_MAX_LAYER_WIDTH];",
        "static int g_affine_exec_count[ISCAS_NUM_LAYERS];",
        "static int g_lif_exec_count[ISCAS_NUM_LAYERS];",
        "static int g_convert_exec_count[ISCAS_NUM_LAYERS];",
        "",
        "void iscas_model_init(void)",
        "{",
        "    memset(g_mem, 0, sizeof(g_mem));",
        "}",
        "",
        "int iscas_model_run(const float *input)",
        "{",
        "    const int last = ISCAS_NUM_LAYERS - 1;",
        "    const int out_dim = ISCAS_LAYERS[last].out_features;",
        "",
        "    /* Every inference starts from zero membranes and counters. */",
        "    for (int l = 0; l < ISCAS_NUM_LAYERS; l++) {",
        "        memset(g_mem[l], 0, (size_t)ISCAS_LAYERS[l].out_features * sizeof(float));",
        "    }",
        "    memset(g_affine_exec_count, 0, sizeof(g_affine_exec_count));",
        "    memset(g_lif_exec_count, 0, sizeof(g_lif_exec_count));",
        "    memset(g_convert_exec_count, 0, sizeof(g_convert_exec_count));",
        "",
        "    float mem_sum[ISCAS_MAX_LAYER_WIDTH];",
        "    memset(mem_sum, 0, (size_t)out_dim * sizeof(float));",
        "",
        "    /* --- Preheader: executes exactly once ------------------------- */",
    ]

    if preheader_lines:
        lines.extend(preheader_lines)
    else:
        lines.append("    /* <empty> -- no op was hoisted into the preheader */")

    lines += [
        "",
        "    /* --- Temporal loop: executes ISCAS_STEPS times ---------------- */",
        "    for (int t = 0; t < ISCAS_STEPS; t++) {",
    ]
    lines.extend("    " + line for line in loop_lines)
    lines += [
        "",
        "        for (int j = 0; j < out_dim; j++) {",
        "            mem_sum[j] += g_mem[last][j];",
        "        }",
        "    }",
        "",
        "    memcpy(g_mem_sum, mem_sum, (size_t)out_dim * sizeof(float));",
        "",
        "    int predicted_class = 0;",
        "    float best = mem_sum[0];",
        "    for (int j = 1; j < out_dim; j++) {",
        "        if (mem_sum[j] > best) {",
        "            best = mem_sum[j];",
        "            predicted_class = j;",
        "        }",
        "    }",
        "    return predicted_class;",
        "}",
        "",
        "#ifdef ISCAS_PORTABLE_EXPOSE_MEMSUM",
        "const float *iscas_model_last_mem_sum(int *out_dim)",
        "{",
        "    *out_dim = ISCAS_LAYERS[ISCAS_NUM_LAYERS - 1].out_features;",
        "    return g_mem_sum;",
        "}",
        "#endif",
        "",
        "int iscas_model_debug_affine_exec_count(int layer)",
        "{",
        "    return g_affine_exec_count[layer];",
        "}",
        "",
        "int iscas_model_debug_lif_exec_count(int layer)",
        "{",
        "    return g_lif_exec_count[layer];",
        "}",
        "",
        "int iscas_model_debug_convert_exec_count(int layer)",
        "{",
        "    return g_convert_exec_count[layer];",
        "}",
        "",
    ]

    return "\n".join(lines)


# Host test harness (include_harness=True), not part of the model API. Protocol on stdin/stdout,
# native byte order: int32 num_samples, then per sample
# (ISCAS_INPUT_TEMPORAL ? ISCAS_STEPS : 1) * ISCAS_INPUT_DIM float32 values; one int32 class out each.
_HARNESS_C = """// Generated by SpikeDuet -- host test harness, NOT the model API
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#ifdef _WIN32
#include <fcntl.h>
#include <io.h>
#endif

#include "portable_runtime.h"

static int read_all(void *buf, size_t n) {
    return fread(buf, 1, n, stdin) == n;
}

int main(void) {
#ifdef _WIN32
    /* The protocol is binary; Windows opens stdio in text mode by default. */
    _setmode(_fileno(stdin), _O_BINARY);
    _setmode(_fileno(stdout), _O_BINARY);
#endif

    iscas_model_init();

    int32_t num_samples = 0;
    if (!read_all(&num_samples, sizeof(num_samples))) {
        fprintf(stderr, "failed to read num_samples header\\n");
        return 1;
    }

    size_t per_sample = (size_t)(ISCAS_INPUT_TEMPORAL ? ISCAS_STEPS : 1) * (size_t)ISCAS_INPUT_DIM;
    float *buf = (float *)malloc(per_sample * sizeof(float));
    if (!buf) {
        fprintf(stderr, "allocation failed\\n");
        return 1;
    }

    for (int32_t s = 0; s < num_samples; s++) {
        if (!read_all(buf, per_sample * sizeof(float))) {
            fprintf(stderr, "failed to read sample %d\\n", s);
            free(buf);
            return 1;
        }
        int32_t predicted = (int32_t)iscas_model_run(buf);
        if (fwrite(&predicted, sizeof(predicted), 1, stdout) != 1) {
            fprintf(stderr, "failed to write result for sample %d\\n", s);
            free(buf);
            return 1;
        }
    }

    fflush(stdout);
    free(buf);
    return 0;
}
"""


class PortableCBackend(Backend):
    """Target-independent scalar C99 backend."""

    name = "portable_c"

    def generate(self, module: ExecutionModule, *, include_harness: bool = False) -> GeneratedArtifact:
        verify_execution_ir(module)

        linear_layers, _ = layer_sequence(module)
        max_layer_width = max(
            [l.in_features for l in linear_layers] + [l.out_features for l in linear_layers]
        )

        files = {
            "model_data.h": render_model_data_header(module, guard=_MODEL_DATA_GUARD),
            "model_config.h": _model_config_header(module, max_layer_width),
            "portable_runtime.h": _RUNTIME_H,
            "portable_runtime.c": _generate_runtime_c(module),
        }
        if include_harness:
            files["main.c"] = _HARNESS_C

        return GeneratedArtifact(files=files)
