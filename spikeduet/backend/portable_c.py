"""Portable-C backend: plain C99 with no vendor dependency.

Generates ``model_data.h`` (shared descriptor table), ``model_config.h`` (timestep count, input
mode, largest layer width), ``portable_runtime.h`` (fixed LIF helpers and the public API) and a
per-model ``portable_runtime.c`` that executes the module's schedule literally: preheader ops once,
loop-body ops on every step. Buffers are static arrays; nothing is allocated at runtime.
``include_harness=True`` adds a host ``main.c`` that reads samples from stdin.
"""


