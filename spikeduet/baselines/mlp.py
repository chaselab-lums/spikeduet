def generate_mlp_firmware(mlp: MLPWeights, *, engine: str = "mvp", num_steps: Optional[int] = None,
                          **options) -> Dict[str, str]:
    """``model_data.h``, ``snn.h`` and ``snn.c`` for an MLP baseline.

    ``num_steps=None`` gives a static engine (one forward pass per inference); an integer gives a
    temporal engine. ``options`` go to ``generate_snn_c_cpu_temporal`` (``engine="cpu"``) or
    ``generate_snn_c_mvp_temporal`` (``engine="mvp"``).
    """
    if engine not in ("cpu", "mvp"):
        raise ValueError(f"engine must be 'cpu' or 'mvp', got {engine!r}")
    if num_steps is None:
        if options:
            raise ValueError(f"options {sorted(options)} apply to temporal engines (num_steps=...)")
        code = generate_snn_c_cpu(mlp) if engine == "cpu" else generate_snn_c_mvp(mlp)
    elif engine == "cpu":
        code = generate_snn_c_cpu_temporal(mlp, num_steps, **options)
    else:
        code = generate_snn_c_mvp_temporal(mlp, num_steps, **options)
    return {"model_data.h": generate_model_data_h(mlp, temporal_steps=num_steps), "snn.h": generate_snn_h(),
            "snn.c": code}
