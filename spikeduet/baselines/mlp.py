"""EFR32 firmware for plain MLP baselines (``Linear -> ReLU -> ... -> Linear``).

Used for SNN-versus-ANN comparisons on the same runtime. It is independent of the SNN IR: an MLP has
no LIF parameters, so it gets its own small ``model_data.h`` (``mlp_layer_t``: dimensions, weight,
bias). The generated engine is still called ``snn.c`` and implements the same entry points as the
SNN engines (``snn_init``, ``run_snn_inference``, ``iscas_infer_reset/step/readout``), so
``runtime/efr32/app.c`` runs it unchanged.

Static generators run one forward pass per inference. Temporal generators run the MLP on every
timestep and sum the logits (the stateless analogue of the SNN's summed-membrane readout).
"""

from dataclasses import dataclass
from typing import Dict, List, Optional, Sequence

import torch

_ALLOC_CHECK_H = """
static inline void *snn_alloc_check(void *ptr, const char *what)
{
    if (ptr == NULL) {
        printf("ALLOC_FAIL:%s\\n", what);
        while (1) { /* halt visibly rather than run with a missing buffer */ }
    }
    return ptr;
}
""".strip("\n")


@dataclass
class MLPWeights:
    """Weights of an MLP as plain Python lists."""

    dims: List[int]  # [input, hidden..., output]
    weights: List[List[List[float]]]  # per layer: [out_features][in_features]
    biases: List[List[float]]  # per layer: [out_features]

    @classmethod
    def from_linears(cls, linears: Sequence[torch.nn.Linear]) -> "MLPWeights":
        """From the model's ``nn.Linear`` layers, in order."""
        dims = [linears[0].in_features] + [l.out_features for l in linears]
        return cls(dims=dims, weights=[l.weight.detach().cpu().tolist() for l in linears],
                   biases=[l.bias.detach().cpu().tolist() for l in linears])

    @classmethod
    def from_named_layers(cls, checkpoint_path: str, layer_names: Sequence[str], dims) -> "MLPWeights":
        """From a checkpoint whose layers are ``{name}.weight`` / ``{name}.bias`` for ``name`` in
        ``layer_names``; the state dict may be wrapped in ``model_state_dict``."""
        state = torch.load(checkpoint_path, map_location="cpu", weights_only=False)
        state = state.get("model_state_dict", state)
        return cls(dims=list(dims), weights=[state[f"{n}.weight"].detach().tolist() for n in layer_names],
                   biases=[state[f"{n}.bias"].detach().tolist() for n in layer_names])

    @classmethod
    def from_state_dict_file(cls, path: str, dims, prefix: str = "linears") -> "MLPWeights":
        """From a checkpoint whose layers are ``{prefix}.{l}.weight`` / ``.bias`` (``nn.ModuleList``)."""
        return cls.from_named_layers(path, [f"{prefix}.{l}" for l in range(len(dims) - 1)], dims)

    @property
    def num_layers(self) -> int:
        return len(self.weights)

    def param_count(self) -> int:
        total = 0
        for l in range(self.num_layers):
            out_f, in_f = self.dims[l + 1], self.dims[l]
            total += out_f * in_f + out_f
        return total


def _c_float_array(name: str, values: List[float]) -> str:
    body = ", ".join(f"{v:.9g}f" for v in values)
    return f"static const float {name}[{len(values)}] = {{{body}}};"


def generate_model_data_h(mlp: MLPWeights, temporal_steps: int = None) -> str:
    lines = [
        "// Generated by SpikeDuet -- do not edit by hand",
        "// MLP baseline: dimensions, weights and biases only (no LIF parameters).",
        "#ifndef MODEL_DATA_H",
        "#define MODEL_DATA_H",
        "",
        "#include <stddef.h>",
        "",
        f"#define ISCAS_INPUT_DIM {mlp.dims[0]}",
        f"#define ISCAS_OUTPUT_DIM {mlp.dims[-1]}",
        f"#define ISCAS_NUM_LAYERS {mlp.num_layers}",
    ]
    if temporal_steps is not None:
        lines += [
            f"#define ISCAS_STEPS {temporal_steps}",
            "#define ISCAS_INPUT_TEMPORAL 1",
        ]
    lines += [
        "",
        "typedef struct {",
        "    int in_features;",
        "    int out_features;",
        "    const float *weight;  /* row-major [out_features][in_features], flattened */",
        "    const float *bias;    /* [out_features] -- MLP layers always have bias */",
        "} mlp_layer_t;",
        "",
    ]
    for l in range(mlp.num_layers):
        out_f, in_f = mlp.dims[l + 1], mlp.dims[l]
        flat_w = [v for row in mlp.weights[l] for v in row]
        lines.append(_c_float_array(f"mlp_layer{l}_weight", flat_w))
        lines.append(_c_float_array(f"mlp_layer{l}_bias", mlp.biases[l]))
        lines.append("")

    lines.append("static const mlp_layer_t MLP_LAYERS[ISCAS_NUM_LAYERS] = {")
    for l in range(mlp.num_layers):
        out_f, in_f = mlp.dims[l + 1], mlp.dims[l]
        lines.append(f"    {{ {in_f}, {out_f}, mlp_layer{l}_weight, mlp_layer{l}_bias }},")
    lines.append("};")
    lines.append("")
    lines.append("#endif  /* MODEL_DATA_H */")
    return "\n".join(lines) + "\n"


def generate_snn_h() -> str:
    return "\n".join(
        [
            "// Generated by SpikeDuet -- do not edit by hand",
            "#ifndef SNN_H",
            "#define SNN_H",
            "",
            "#include <stdio.h>",
            "",
            _ALLOC_CHECK_H,
            "",
            "void snn_init(void);",
            "int run_snn_inference(float *input_data);",
            "void iscas_infer_reset(const float *first_input);",
            "void iscas_infer_step(const float *step_input);",
            "int iscas_infer_readout(void);",
            "",
            "#endif  /* SNN_H */",
            "",
        ]
    )


def generate_snn_c_cpu(mlp: MLPWeights) -> str:
    n = mlp.num_layers
    lines = [
        "// Generated by SpikeDuet -- do not edit by hand",
        "/* MLP CPU engine: one forward pass per inference (affine, ReLU on hidden layers), argmax. */",
        '#include "model_data.h"',
        '#include "snn.h"',
        "#include <stdlib.h>",
        "",
        "static float *g_act[ISCAS_NUM_LAYERS];  /* per-layer output activations */",
        "",
        "void snn_init(void)",
        "{",
        "    for (int l = 0; l < ISCAS_NUM_LAYERS; l++) {",
        "        g_act[l] = (float *)snn_alloc_check(",
        '            malloc((size_t)MLP_LAYERS[l].out_features * sizeof(float)), "g_act[l]");',
        "    }",
        "}",
        "",
        "int run_snn_inference(float *input_data)",
        "{",
        "    const float *cur_input = input_data;",
        "    for (int l = 0; l < ISCAS_NUM_LAYERS; l++) {",
        "        const mlp_layer_t *L = &MLP_LAYERS[l];",
        "        for (int j = 0; j < L->out_features; j++) {",
        "            float acc = L->bias[j];",
        "            for (int i = 0; i < L->in_features; i++) {",
        "                acc += L->weight[(size_t)j * L->in_features + i] * cur_input[i];",
        "            }",
        f"            g_act[l][j] = (l < {n} - 1 && acc < 0.0f) ? 0.0f : acc;  /* ReLU on all but the last layer */",
        "        }",
        "        cur_input = g_act[l];",
        "    }",
        "",
        f"    const float *logits = g_act[{n} - 1];",
        f"    const int out_dim = MLP_LAYERS[{n} - 1].out_features;",
        "    int predicted_class = 0;",
        "    float best = logits[0];",
        "    for (int j = 1; j < out_dim; j++) {",
        "        if (logits[j] > best) { best = logits[j]; predicted_class = j; }",
        "    }",
        "    return predicted_class;",
        "}",
        "",
    ]
    return "\n".join(lines)


def generate_snn_c_mvp(mlp: MLPWeights) -> str:
    n = mlp.num_layers
    lines = [
        "// Generated by SpikeDuet -- do not edit by hand",
        "/* MLP MVP engine: one forward pass per inference. Weights cast to FP16 once in snn_init(),",
        " * one MVP matvec per layer, FP32 bias and ReLU on the CPU, argmax. */",
        '#include "model_data.h"',
        '#include "snn.h"',
        '#include "sl_math_mvp.h"',
        "#include <stdlib.h>",
        "",
        "static sl_math_matrix_f16_t g_mat[ISCAS_NUM_LAYERS];",
        "static float16_t *g_weight_f16[ISCAS_NUM_LAYERS];",
        "static float16_t *g_in_f16[ISCAS_NUM_LAYERS];",
        "static float16_t *g_cur_f16[ISCAS_NUM_LAYERS];",
        "static float *g_act[ISCAS_NUM_LAYERS];  /* post-bias, post-ReLU FP32 activations */",
        "",
        "void snn_init(void)",
        "{",
        "    for (int l = 0; l < ISCAS_NUM_LAYERS; l++) {",
        "        const mlp_layer_t *L = &MLP_LAYERS[l];",
        "        const size_t n_weights = (size_t)L->out_features * (size_t)L->in_features;",
        "        g_weight_f16[l] = (float16_t *)snn_alloc_check(",
        '            malloc(n_weights * sizeof(float16_t)), "g_weight_f16[l]");',
        "        for (size_t idx = 0; idx < n_weights; idx++) {",
        "            g_weight_f16[l][idx] = (float16_t)L->weight[idx];",
        "        }",
        "        sl_math_matrix_init_f16(&g_mat[l], L->out_features, L->in_features, g_weight_f16[l]);",
        "        g_in_f16[l] = (float16_t *)snn_alloc_check(",
        '            malloc((size_t)L->in_features * sizeof(float16_t)), "g_in_f16[l]");',
        "        g_cur_f16[l] = (float16_t *)snn_alloc_check(",
        '            malloc((size_t)L->out_features * sizeof(float16_t)), "g_cur_f16[l]");',
        "        g_act[l] = (float *)snn_alloc_check(",
        '            malloc((size_t)L->out_features * sizeof(float)), "g_act[l]");',
        "    }",
        "}",
        "",
        "int run_snn_inference(float *input_data)",
        "{",
        "    const float *cur_input = input_data;",
        "    for (int l = 0; l < ISCAS_NUM_LAYERS; l++) {",
        "        const mlp_layer_t *L = &MLP_LAYERS[l];",
        "        for (int i = 0; i < L->in_features; i++) { g_in_f16[l][i] = (float16_t)cur_input[i]; }",
        "        sl_math_mvp_matrix_vector_mult_f16(&g_mat[l], g_in_f16[l], g_cur_f16[l]);",
        "        for (int j = 0; j < L->out_features; j++) {",
        "            float acc = (float)g_cur_f16[l][j] + L->bias[j];",
        f"            g_act[l][j] = (l < {n} - 1 && acc < 0.0f) ? 0.0f : acc;  /* ReLU on all but the last layer */",
        "        }",
        "        cur_input = g_act[l];",
        "    }",
        "",
        f"    const float *logits = g_act[{n} - 1];",
        f"    const int out_dim = MLP_LAYERS[{n} - 1].out_features;",
        "    int predicted_class = 0;",
        "    float best = logits[0];",
        "    for (int j = 1; j < out_dim; j++) {",
        "        if (logits[j] > best) { best = logits[j]; predicted_class = j; }",
        "    }",
        "    return predicted_class;",
        "}",
        "",
    ]
    return "\n".join(lines)


def generate_snn_c_cpu_temporal(mlp: MLPWeights, num_steps: int, per_layer_blocks: bool = False) -> str:
    """Temporal MLP, Cortex-M33 FP32: the MLP runs on every timestep and the logits are summed.

    ``per_layer_blocks=True`` emits one block per layer with literal indices, the same loop shape as
    the SNN backend's scalar affine. Use it for CPU comparisons: the default runtime-indexed layer
    loop compiles to slower inner loops at ``-Os``.
    """
    n = mlp.num_layers
    out_dim = mlp.dims[-1]
    if per_layer_blocks:
        step_body = []
        for l in range(n):
            relu = l < n - 1
            src = "step_input" if l == 0 else f"g_act[{l - 1}]"
            step_body += [
                f"    {{ /* layer {l}: dense scalar affine{' + ReLU' if relu else ''} */",
                f"        const mlp_layer_t *L = &MLP_LAYERS[{l}];",
                "        for (int j = 0; j < L->out_features; j++) {",
                "            float c = L->bias[j];",
                "            for (int i = 0; i < L->in_features; i++) {",
                f"                c += L->weight[(size_t)j * L->in_features + i] * {src}[i];",
                "            }",
                f"            g_act[{l}][j] = {'(c < 0.0f) ? 0.0f : c' if relu else 'c'};",
                "        }",
                "    }",
            ]
    else:
        step_body = [
            "    const float *cur_input = step_input;",
            "    for (int l = 0; l < ISCAS_NUM_LAYERS; l++) {",
            "        const mlp_layer_t *L = &MLP_LAYERS[l];",
            "        for (int j = 0; j < L->out_features; j++) {",
            "            float acc = L->bias[j];",
            "            for (int i = 0; i < L->in_features; i++) {",
            "                acc += L->weight[(size_t)j * L->in_features + i] * cur_input[i];",
            "            }",
            f"            g_act[l][j] = (l < {n} - 1 && acc < 0.0f) ? 0.0f : acc;  /* ReLU on all but the last layer */",
            "        }",
            "        cur_input = g_act[l];",
            "    }",
        ]
    lines = [
        "// Generated by SpikeDuet -- do not edit by hand",
        "/* Temporal MLP CPU engine: the MLP runs on every timestep, logits are summed, argmax at the end. */",
        '#include "model_data.h"',
        '#include "snn.h"',
        "#include <stdlib.h>",
        "#include <string.h>",
        "",
        "static float *g_act[ISCAS_NUM_LAYERS];",
        f"static float g_logit_sum[{out_dim}];",
        "",
        "void snn_init(void)",
        "{",
        "    for (int l = 0; l < ISCAS_NUM_LAYERS; l++) {",
        "        g_act[l] = (float *)snn_alloc_check(",
        '            malloc((size_t)MLP_LAYERS[l].out_features * sizeof(float)), "g_act[l]");',
        "    }",
        "}",
        "",
        "void iscas_infer_reset(const float *first_input)",
        "{",
        "    (void)first_input;",
        "    memset(g_logit_sum, 0, sizeof(g_logit_sum));",
        "}",
        "",
        "void iscas_infer_step(const float *step_input)",
        "{",
        *step_body,
        f"    for (int j = 0; j < {out_dim}; j++) {{ g_logit_sum[j] += g_act[{n} - 1][j]; }}",
        "}",
        "",
        "int iscas_infer_readout(void)",
        "{",
        "    int predicted_class = 0;",
        "    float best = g_logit_sum[0];",
        f"    for (int j = 1; j < {out_dim}; j++) {{",
        "        if (g_logit_sum[j] > best) { best = g_logit_sum[j]; predicted_class = j; }",
        "    }",
        "    return predicted_class;",
        "}",
        "",
        "int run_snn_inference(float *input_data)",
        "{",
        "    iscas_infer_reset(input_data);",
        f"    for (int t = 0; t < {num_steps}; t++) {{",
        "        iscas_infer_step(input_data + (size_t)t * ISCAS_INPUT_DIM);",
        "    }",
        "    return iscas_infer_readout();",
        "}",
        "",
    ]
    return "\n".join(lines)


def _sparse_input_layer_lines(mlp: MLPWeights) -> List[str]:
    """Layer 0 with the SNN backend's range-sparse MVP kernel (same launch helpers, merge gap and
    runtime guard), followed by bias and ReLU. Bitwise equal to the dense SDK matvec."""
    from spikeduet.backend.efr32.mvp_sparse import EFR32_MVP_MAX_DIM, fp32_merge_gap_pairs

    m, n = mlp.dims[1], mlp.dims[0]
    assert n % 2 == 0 and m <= EFR32_MVP_MAX_DIM and n // 2 <= EFR32_MVP_MAX_DIM
    npr, gap = n // 2, fp32_merge_gap_pairs(m)
    relu = "(acc < 0.0f) ? 0.0f : acc" if mlp.num_layers > 1 else "acc"
    return [
        f"    {{ /* layer 0: MVP, range-merged sparse, gap {gap} pairs (same kernel as the SNN backend) */",
        "        const mlp_layer_t *L = &MLP_LAYERS[0];",
        "        const float *src = step_input;",
        "        const uint32_t *xb = (const uint32_t *)src;  /* +0.0f is all-zero bits; -0.0f counts as active (extra work only) */",
        "        uint16_t *rs = g_sparse_rs[0], *re = g_sparse_re[0];",
        "        int nr = 0, span = 0;",
        f"        for (int p = 0; p < {npr}; p++) {{",
        "            if ((xb[2 * p] | xb[2 * p + 1]) != 0u) {",
        f"                if (nr > 0 && p - (int)re[nr - 1] <= {gap}) {{ span += p + 1 - (int)re[nr - 1]; re[nr - 1] = (uint16_t)(p + 1); }}",
        "                else { rs[nr] = (uint16_t)p; re[nr] = (uint16_t)(p + 1); nr++; span++; }",
        "            }",
        "        }",
        "        g_sparse_range_count[0] += nr;",
        "        if (nr == 0) {",
        "            g_sparse_empty_count[0]++;",
        f"            for (int j = 0; j < {m}; j++) {{ float acc = 0.0f + L->bias[j]; g_act[0][j] = {relu}; }}",
        "        } else {",
        "            /* runtime guard (measured cost model): never pay more launches than one dense launch */",
        f"            if ((int32_t)nr * ISCAS_SP_LAUNCH_CYCLES + (int32_t)span * ({m} + ISCAS_SP_STAGE_CYCLES_PER_PAIR)",
        f"                >= ISCAS_SP_LAUNCH_CYCLES + (int32_t){npr} * ({m} + ISCAS_SP_STAGE_CYCLES_PER_PAIR)) {{",
        f"                nr = 1; rs[0] = 0; re[0] = {npr}; span = {npr}; g_sparse_fallback_count[0]++;",
        "            }",
        "            for (int r = 0; r < nr; r++) {",
        "                for (int i = 2 * (int)rs[r]; i < 2 * (int)re[r]; i++) { g_in_f16[0][i] = (float16_t)src[i]; }",
        "            }",
        "            iscas_sp_enter();",
        f"            iscas_sp_setup({m}, {npr}, g_cur_f16[0], g_sparse_acc[0]);",
        "            for (int r = 0; r < nr; r++) {",
        "                iscas_sp_launch(g_weight_f16[0], g_in_f16[0], rs[r], re[r] - rs[r], r == 0, r == nr - 1);",
        "            }",
        "            iscas_sp_exit();",
        "            g_sparse_launch_count[0] += nr;",
        "            g_sparse_pair_count[0] += span;",
        f"            for (int j = 0; j < {m}; j++) {{ float acc = (float)g_cur_f16[0][j] + L->bias[j]; g_act[0][j] = {relu}; }}",
        "        }",
        "#ifdef ISCAS_SPARSE_VERIFY",
        "        {   /* correctness build only (never timed): recompute with the deployed dense SDK kernel, compare bitwise */",
        f"            for (int i = 0; i < {n}; i++) {{ g_in_f16[0][i] = (float16_t)src[i]; }}",
        "            sl_math_mvp_matrix_vector_mult_f16(&g_mat[0], g_in_f16[0], g_sparse_ref[0]);",
        "            const uint16_t *a = (const uint16_t *)g_sparse_ref[0];",
        "            const uint16_t *b = (const uint16_t *)g_cur_f16[0];",
        "            int bad = 0;",
        f"            for (int j = 0; j < {m}; j++) {{ bad |= (nr == 0) ? (a[j] != 0u) : (a[j] != b[j]); }}",
        "            g_sparse_verify_mismatch[0] += bad;",
        "        }",
        "#endif",
        "    }",
    ]


def generate_snn_c_mvp_temporal(mlp: MLPWeights, num_steps: int, sparse_input_layer: bool = False,
                                static_io_layers=(), event_input_layer: bool = False,
                                reuse_empty_frames: bool = False, stage_profile: bool = False,
                                event_weights: Optional[str] = None, mvp_flash_weight_layers=(),
                                mvp_split_rows=None, fold_output_affine: bool = False) -> str:
    """Temporal MLP on the MVP: every timestep runs the MLP (FP16 matvecs, FP32 bias and ReLU), the
    logits are summed, argmax at the end.

    Options (all off by default):
        sparse_input_layer: layer 0 with the range-sparse MVP kernel.
        static_io_layers: FP16 input/output vectors of these layers in static memory.
        event_input_layer: layer 0 event-driven on the Cortex-M33 (the SNN backend's kernel).
        reuse_empty_frames: the logits of an all-zero frame are computed once in ``snn_init()``;
            empty frames reuse them and skip every layer (exact).
        stage_profile: DWT stage markers (``ISCAS_STAGE_PROFILE`` builds).
        event_weights: ``"sram"`` or ``"flash"`` residency of the event layer's weights.
        mvp_flash_weight_layers: these layers' FP16 weights stay in flash and the MVP reads them in
            place.
        mvp_split_rows: ``{layer: R}`` keeps rows ``0..R-1`` in SRAM and reads the rest from flash.
        fold_output_affine: the last layer runs once per inference on the summed penultimate
            activations (requires ``reuse_empty_frames``).

    ``event_input_layer``, ``reuse_empty_frames`` or ``stage_profile`` select the per-layer
    generator that supports the memory and folding options.
    """
    if event_weights is not None and not event_input_layer:
        raise ValueError("event_weights applies to event_input_layer=True")
    if (mvp_flash_weight_layers or mvp_split_rows or fold_output_affine) and not (event_input_layer or reuse_empty_frames or stage_profile):
        raise ValueError("mvp_flash_weight_layers applies to the fair-MLP generator (event_input_layer/reuse/stage_profile)")
    if event_input_layer or reuse_empty_frames or stage_profile:
        assert not sparse_input_layer, "the fair-MLP generator realizes layer 0 on the M33 or dense MVP, not range-sparse"
        return _generate_mlp_temporal_fair(mlp, num_steps, event_input_layer, reuse_empty_frames,
                                           frozenset(static_io_layers), stage_profile, event_weights,
                                           frozenset(mvp_flash_weight_layers), dict(mvp_split_rows or {}), fold_output_affine)
    if static_io_layers:
        return _with_static_io(generate_snn_c_mvp_temporal(mlp, num_steps, sparse_input_layer), mlp, static_io_layers)
    if sparse_input_layer:
        return _generate_snn_c_mvp_temporal_sparse(mlp, num_steps)
    n = mlp.num_layers
    out_dim = mlp.dims[-1]
    lines = [
        "// Generated by SpikeDuet -- do not edit by hand",
        "/* Temporal MLP MVP engine: the MLP runs on every timestep, logits are summed, argmax at the end. */",
        '#include "model_data.h"',
        '#include "snn.h"',
        '#include "sl_math_mvp.h"',
        "#include <stdlib.h>",
        "#include <string.h>",
        "",
        "static sl_math_matrix_f16_t g_mat[ISCAS_NUM_LAYERS];",
        "static float16_t *g_weight_f16[ISCAS_NUM_LAYERS];",
        "static float16_t *g_in_f16[ISCAS_NUM_LAYERS];",
        "static float16_t *g_cur_f16[ISCAS_NUM_LAYERS];",
        "static float *g_act[ISCAS_NUM_LAYERS];",
        f"static float g_logit_sum[{out_dim}];",
        "",
        "void snn_init(void)",
        "{",
        "    for (int l = 0; l < ISCAS_NUM_LAYERS; l++) {",
        "        const mlp_layer_t *L = &MLP_LAYERS[l];",
        "        const size_t n_weights = (size_t)L->out_features * (size_t)L->in_features;",
        "        g_weight_f16[l] = (float16_t *)snn_alloc_check(",
        '            malloc(n_weights * sizeof(float16_t)), "g_weight_f16[l]");',
        "        for (size_t idx = 0; idx < n_weights; idx++) {",
        "            g_weight_f16[l][idx] = (float16_t)L->weight[idx];",
        "        }",
        "        sl_math_matrix_init_f16(&g_mat[l], L->out_features, L->in_features, g_weight_f16[l]);",
        "        g_in_f16[l] = (float16_t *)snn_alloc_check(",
        '            malloc((size_t)L->in_features * sizeof(float16_t)), "g_in_f16[l]");',
        "        g_cur_f16[l] = (float16_t *)snn_alloc_check(",
        '            malloc((size_t)L->out_features * sizeof(float16_t)), "g_cur_f16[l]");',
        "        g_act[l] = (float *)snn_alloc_check(",
        '            malloc((size_t)L->out_features * sizeof(float)), "g_act[l]");',
        "    }",
        "}",
        "",
        "void iscas_infer_reset(const float *first_input)",
        "{",
        "    (void)first_input;",
        "    memset(g_logit_sum, 0, sizeof(g_logit_sum));",
        "}",
        "",
        "void iscas_infer_step(const float *step_input)",
        "{",
        "    const float *cur_input = step_input;",
        "    for (int l = 0; l < ISCAS_NUM_LAYERS; l++) {",
        "        const mlp_layer_t *L = &MLP_LAYERS[l];",
        "        for (int i = 0; i < L->in_features; i++) { g_in_f16[l][i] = (float16_t)cur_input[i]; }",
        "        sl_math_mvp_matrix_vector_mult_f16(&g_mat[l], g_in_f16[l], g_cur_f16[l]);",
        "        for (int j = 0; j < L->out_features; j++) {",
        "            float acc = (float)g_cur_f16[l][j] + L->bias[j];",
        f"            g_act[l][j] = (l < {n} - 1 && acc < 0.0f) ? 0.0f : acc;  /* ReLU on all but the last layer */",
        "        }",
        "        cur_input = g_act[l];",
        "    }",
        f"    for (int j = 0; j < {out_dim}; j++) {{ g_logit_sum[j] += g_act[{n} - 1][j]; }}",
        "}",
        "",
        "int iscas_infer_readout(void)",
        "{",
        "    int predicted_class = 0;",
        "    float best = g_logit_sum[0];",
        f"    for (int j = 1; j < {out_dim}; j++) {{",
        "        if (g_logit_sum[j] > best) { best = g_logit_sum[j]; predicted_class = j; }",
        "    }",
        "    return predicted_class;",
        "}",
        "",
        "int run_snn_inference(float *input_data)",
        "{",
        "    iscas_infer_reset(input_data);",
        f"    for (int t = 0; t < {num_steps}; t++) {{",
        "        iscas_infer_step(input_data + (size_t)t * ISCAS_INPUT_DIM);",
        "    }",
        "    return iscas_infer_readout();",
        "}",
        "",
    ]
    return "\n".join(lines)


def _with_static_io(code: str, mlp: MLPWeights, layers) -> str:
    """Moves the listed layers' FP16 I/O vectors to static memory, as the SNN backend's
    ``mvp_static_io_layers`` does. The heap allocations are kept so no other address moves."""
    nl = "\n"
    decl = "".join(f"static float16_t g_io_in{l}[{mlp.dims[l]}] __attribute__((aligned(4)));  /* static I/O */{nl}"
                   f"static float16_t g_io_cur{l}[{mlp.dims[l + 1]}] __attribute__((aligned(4))){';'}{nl}" for l in sorted(layers))
    init = "".join(f"    g_in_f16[{l}] = g_io_in{l}; g_cur_f16[{l}] = g_io_cur{l};   /* static I/O */{nl}"
                   for l in sorted(layers))
    a_decl = "static float *g_act[ISCAS_NUM_LAYERS];" + nl
    a_init = nl + "}" + nl + nl + "void iscas_infer_reset"      # end of snn_init()
    assert code.count(a_decl) == 1 and code.count(a_init) == 1
    code = code.replace(a_decl, a_decl + decl)
    return code.replace(a_init, nl + init.rstrip(nl) + nl + "}" + nl + nl + "void iscas_infer_reset")


def _generate_snn_c_mvp_temporal_sparse(mlp: MLPWeights, num_steps: int) -> str:
    """The dense temporal MVP engine with layer 0 replaced by ``_sparse_input_layer_lines``."""
    from spikeduet.backend.efr32.mvp_sparse import SPARSE_MVP_HELPERS

    dense = generate_snn_c_mvp_temporal(mlp, num_steps)
    m, npr = mlp.dims[1], mlp.dims[0] // 2
    counters = ("launch", "pair", "range", "empty", "fallback")
    decl = [
        '#include "sl_mvp.h"',
        '#include "em_device.h"',
        "#include <stdint.h>",
        "static float16_t *g_sparse_acc[ISCAS_NUM_LAYERS];   /* per-row FP16 (even, odd) lane accumulator pairs */",
        "static uint16_t *g_sparse_rs[ISCAS_NUM_LAYERS];     /* merged active pair ranges [rs, re) */",
        "static uint16_t *g_sparse_re[ISCAS_NUM_LAYERS];",
        "#ifdef ISCAS_SPARSE_VERIFY",
        "static float16_t *g_sparse_ref[ISCAS_NUM_LAYERS];",
        "#endif",
        *[f"static int g_sparse_{c}_count[ISCAS_NUM_LAYERS];" for c in counters],
        "static int g_sparse_verify_mismatch[ISCAS_NUM_LAYERS];",
        SPARSE_MVP_HELPERS,
    ]
    init = [
        f'    g_sparse_acc[0] = (float16_t *)snn_alloc_check(malloc((size_t){2 * m} * sizeof(float16_t)), "g_sparse_acc");',
        f'    g_sparse_rs[0] = (uint16_t *)snn_alloc_check(malloc((size_t){npr} * sizeof(uint16_t)), "g_sparse_rs");',
        f'    g_sparse_re[0] = (uint16_t *)snn_alloc_check(malloc((size_t){npr} * sizeof(uint16_t)), "g_sparse_re");',
        "#ifdef ISCAS_SPARSE_VERIFY",
        f'    g_sparse_ref[0] = (float16_t *)snn_alloc_check(malloc((size_t){m} * sizeof(float16_t)), "g_sparse_ref");',
        "#endif",
    ]
    step_old = [
        "    const float *cur_input = step_input;",
        "    for (int l = 0; l < ISCAS_NUM_LAYERS; l++) {",
    ]
    step_new = [
        *_sparse_input_layer_lines(mlp),
        "    const float *cur_input = g_act[0];",
        "    for (int l = 1; l < ISCAS_NUM_LAYERS; l++) {",
    ]
    reset_old = "    memset(g_logit_sum, 0, sizeof(g_logit_sum));"
    reset_new = "\n".join([reset_old, *[f"    memset(g_sparse_{c}_count, 0, sizeof(g_sparse_{c}_count));" for c in counters],
                           "    memset(g_sparse_verify_mismatch, 0, sizeof(g_sparse_verify_mismatch));"])
    accessors = [
        *[f"int iscas_debug_sparse_{c}_count(int layer) {{ return g_sparse_{c}_count[layer]; }}" for c in counters],
        "int iscas_debug_sparse_verify_mismatch(int layer) { return g_sparse_verify_mismatch[layer]; }",
        "int iscas_debug_sparse_mvp_fault(void) { return g_sparse_mvp_fault; }",
        "int iscas_debug_sparse_layer(int layer) { return layer == 0; }",
    ]
    s = dense
    anchor_decl = "static float *g_act[ISCAS_NUM_LAYERS];\n"
    anchor_init = "    }\n}\n\nvoid iscas_infer_reset"
    step_block = "\n".join(step_old)
    assert s.count(anchor_decl) == 1 and s.count(anchor_init) == 1 and s.count(step_block) == 1 and s.count(reset_old) == 1
    s = s.replace(anchor_decl, anchor_decl + "\n".join(decl) + "\n")
    s = s.replace(anchor_init, "    }\n" + "\n".join(init) + "\n}\n\nvoid iscas_infer_reset")
    s = s.replace(step_block, "\n".join(step_new))
    s = s.replace(reset_old, reset_new)
    s = s.replace("// Generated by SpikeDuet -- do not edit by hand",
                  "// Generated by SpikeDuet -- do not edit by hand\n"
                  "// Layer 0: range-merged sparse MVP", 1)
    return s.rstrip("\n") + "\n" + "\n".join(accessors) + "\n"


def _generate_mlp_temporal_fair(mlp: MLPWeights, num_steps: int, event_input_layer: bool, reuse_empty_frames: bool,
                                static_io_layers, stage_profile: bool, event_weights: Optional[str] = None,
                                mvp_flash_weight_layers=frozenset(), mvp_split_rows=None, fold_output_affine: bool = False) -> str:
    """Per-layer temporal MLP generator (see ``generate_snn_c_mvp_temporal`` for the options).

    Layer 0 runs event-driven on the Cortex-M33 or as a dense MVP matvec; later layers are dense MVP
    with FP32 bias and ReLU. ``ISCAS_SPARSE_VERIFY`` builds recompute the event layer and every
    reused frame and count bitwise mismatches.
    """
    from spikeduet.backend.efr32.cpu_sparse import CPU_SPARSE_HELPERS, cpu_sparse_init_lines, cpu_sparse_layer_definitions

    n, out_dim, n0 = mlp.num_layers, mlp.dims[-1], mlp.dims[0]
    assert n >= 2 and n0 % 2 == 0
    first_mvp = 1 if event_input_layer else 0
    assert set(static_io_layers) <= set(range(first_mvp, n)), "static I/O applies to MVP layers only"
    flash_w = frozenset(mvp_flash_weight_layers)
    assert flash_w <= set(range(first_mvp, n)), "mvp_flash_weight_layers applies to MVP layers only"
    split = dict(mvp_split_rows or {})
    assert set(split) <= set(range(first_mvp, n)) and not (set(split) & flash_w), "split layers: MVP layers, not also all-flash"
    for l, r_ in split.items():
        assert 0 < r_ < mlp.dims[l + 1] and r_ % 2 == 0, "split rows: even, 0 < R < out_features (4-byte aligned output offset)"
    names: List[str] = []

    def lap(name: str, ind: str) -> List[str]:
        if not stage_profile:
            return []
        if name not in names:
            names.append(name)
        return [f"{ind}ISCAS_PROF_LAP({names.index(name)});  /* stage: {name} */"]

    lit = lambda v: f"{v:.9g}f"          # the SAME literal format as this module's model_data.h
    act = lambda l: f"g_act[{l}]"
    relu = lambda l: "(acc < 0.0f) ? 0.0f : acc" if l < n - 1 else "acc"

    decl = [
        "// Generated by SpikeDuet -- do not edit by hand",
        "/* Temporal MLP: the MLP runs on every timestep, logits summed over all timesteps, argmax at the end.",
        f" * layer 0: {'Cortex-M33 event-driven' if event_input_layer else 'dense MVP'};"
        f" layers {first_mvp}..{n - 1}: dense MVP FP16 (static I/O: {sorted(static_io_layers) or 'none'});"
        f" empty-frame reuse: {'on' if reuse_empty_frames else 'off'}. */",
        '#include "model_data.h"', '#include "snn.h"', '#include "sl_math_mvp.h"',
        "#include <stdint.h>", "#include <stdlib.h>", "#include <string.h>", "",
        "static sl_math_matrix_f16_t g_mat[ISCAS_NUM_LAYERS];",
        "static float16_t *g_weight_f16[ISCAS_NUM_LAYERS];",
        "static float16_t *g_in_f16[ISCAS_NUM_LAYERS];",
        "static float16_t *g_cur_f16[ISCAS_NUM_LAYERS];",
        "static float *g_act[ISCAS_NUM_LAYERS];",
        f"static float g_logit_sum[{out_dim}];",
    ]
    for l in sorted(static_io_layers):
        decl += [f"static float16_t g_io_in{l}[{mlp.dims[l]}] __attribute__((aligned(4)));  /* static I/O */",
                 f"static float16_t g_io_cur{l}[{mlp.dims[l + 1]}] __attribute__((aligned(4)));"]
    if fold_output_affine:
        assert reuse_empty_frames, "fold_output_affine is implemented together with exact empty-frame reuse"
        decl += [f"static float g_fold_hsum[{mlp.dims[n - 1]}];   /* penultimate activations summed over non-empty frames */",
                 "static int g_fold_n, g_fold_empty;",
                 "static const float *mlp_final(const float *h);"]
    if reuse_empty_frames:
        decl += [f"static float g_empty_logits[{out_dim}];   /* logits of an all-zero frame, computed once in snn_init() */",
                 f"static const float g_zero_frame[{n0}] = {{0.0f}};", "static int g_mlp_reused_frames;"]
    if flash_w:
        decl += _flash_weight_tables(mlp, flash_w)
    if split:
        decl += _split_weight_tables(mlp, split)
    if event_input_layer:
        decl += CPU_SPARSE_HELPERS.strip("\n").split("\n")
        decl += cpu_sparse_layer_definitions(0, mlp.dims[1], n0, mlp.weights[0], "mlp_layer0_bias", lit)
    else:
        decl += ["static int g_csp_verify_mismatch[ISCAS_NUM_LAYERS];"] if reuse_empty_frames else []
    if stage_profile:
        decl += ["#ifdef ISCAS_STAGE_PROFILE", '#include "em_device.h"', "#define ISCAS_PROF_MAX 64",
                 "static uint32_t g_prof_cycles[ISCAS_PROF_MAX];", "static uint32_t g_prof_t;",
                 "#define ISCAS_PROF_START() (g_prof_t = DWT->CYCCNT)",
                 "#define ISCAS_PROF_LAP(s) do { uint32_t _n = DWT->CYCCNT; g_prof_cycles[(s)] += _n - g_prof_t; g_prof_t = _n; } while (0)",
                 "#else", "#define ISCAS_PROF_START() ((void)0)", "#define ISCAS_PROF_LAP(s) ((void)0)", "#endif"]

    # ---- mlp_eval(): one timestep's forward pass; returns the final-layer outputs to accumulate
    body = ["static const float *mlp_eval(const float *x, int allow_reuse)", "{",
            "    (void)allow_reuse;" if not reuse_empty_frames else ""]
    if event_input_layer:
        body += ["    {   /* layer 0: Cortex-M33 event-driven, FP32 */",
                 "        int all_ones;",
                 f"        const int k = iscas_csp_scan(x, {n0}, g_csp_idx[0], &all_ones);",
                 *lap("affine0.plan", "        ")]
        empty_test = "k == 0"
    else:
        body += ["    {   /* layer 0: dense MVP */"]
        if reuse_empty_frames:
            body += ["        const uint32_t *xb = (const uint32_t *)x;", "        uint32_t any = 0u;",
                     f"        for (int i = 0; i < {n0}; i++) {{ any |= xb[i]; }}"]
        empty_test = "any == 0u"
    if reuse_empty_frames:
        keep = ("const int e0 = g_csp_empty_count[0], nb0 = g_csp_nonbinary_count[0]; ", "g_csp_empty_count[0] = e0; g_csp_nonbinary_count[0] = nb0; ") \
            if event_input_layer else ("", "")
        body += [f"        if (allow_reuse && {empty_test}) {{   /* exact: identical to recomputing an all-zero frame */",
                 "            g_mlp_reused_frames++;",
                 *(["            g_csp_empty_count[0]++;"] if event_input_layer else []),
                 "#ifdef ISCAS_SPARSE_VERIFY",
                 f"            {{   {keep[0]}const float *full = mlp_eval(x, 0);   /* full recompute, counters restored */",
                 (f"                g_csp_verify_mismatch[0] += memcmp(mlp_final(full), g_empty_logits, sizeof(g_empty_logits)) != 0; {keep[1]}}}"
                  if fold_output_affine else
                  f"                g_csp_verify_mismatch[0] += memcmp(full, g_empty_logits, sizeof(g_empty_logits)) != 0; {keep[1]}}}"),
                 "#endif",
                 *lap("reuse", "            "),
                 ("            return 0;   /* folded: the empty-frame contribution is added once, in the readout */"
                  if fold_output_affine else "            return g_empty_logits;"),
                 "        }"]
    if event_input_layer:
        h0 = mlp.dims[1]
        body += ["        iscas_csp_acc0(g_csp_wT[0], g_csp_idx[0], k, all_ones ? 0 : x, g_act[0]);",
                 "        g_csp_event_count[0] += k;", "        if (k == 0) { g_csp_empty_count[0]++; }",
                 "        if (!all_ones) { g_csp_nonbinary_count[0]++; }",
                 *lap("affine0.compute", "        "),
                 "#ifdef ISCAS_SPARSE_VERIFY",
                 "        {   /* correctness build only: dense FP32 recompute exactly as the scalar realization, bitwise compare */",
                 "            int bad = 0;",
                 f"            for (int j = 0; j < {h0}; j++) {{",
                 "                float c = mlp_layer0_bias[j];",
                 f"                for (int i = 0; i < {n0}; i++) {{ c += mlp_layer0_weight[(size_t)j * {n0} + i] * x[i]; }}",
                 "                bad |= memcmp(&c, &g_act[0][j], sizeof(float)) != 0;",
                 "            }",
                 "            g_csp_verify_mismatch[0] += bad;",
                 "        }",
                 "#endif",
                 f"        for (int j = 0; j < {h0}; j++) {{ const float acc = g_act[0][j]; g_act[0][j] = {relu(0)}; }}",
                 *lap("act0", "        "),
                 "    }"]
    else:
        body += [f"        for (int i = 0; i < {n0}; i++) {{ g_in_f16[0][i] = (float16_t)x[i]; }}",
                 *lap("affine0.stage", "        "),
                 "        sl_math_mvp_matrix_vector_mult_f16(&g_mat[0], g_in_f16[0], g_cur_f16[0]);",
                 *lap("affine0.mvp", "        "),
                 f"        for (int j = 0; j < {mlp.dims[1]}; j++) {{ const float acc = (float)g_cur_f16[0][j] + mlp_layer0_bias[j]; g_act[0][j] = {relu(0)}; }}",
                 *lap("affine0.out", "        "),
                 "    }"]
    final_fn: List[str] = []
    for l in range(1, n):
        folded = fold_output_affine and l == n - 1
        src = "h" if folded else act(l - 1)
        blk = [f"    {{   /* layer {l}: dense MVP FP16 ({'static' if l in static_io_layers else 'heap'} I/O)"
               + (" -- FOLDED: once per inference */" if folded else " */"),
                 f"        for (int i = 0; i < {mlp.dims[l]}; i++) {{ g_in_f16[{l}][i] = (float16_t){src}[i]; }}",
                 *lap(f"affine{l}.stage", "        "),
                 *([f"        sl_math_mvp_matrix_vector_mult_f16(&g_mat[{l}], g_in_f16[{l}], g_cur_f16[{l}]);   /* rows 0..{split[l] - 1}: SRAM W */",
                    f"        sl_math_mvp_matrix_vector_mult_f16(&g_mat_tail[{l}], g_in_f16[{l}], g_cur_f16[{l}] + {split[l]});   /* rows {split[l]}..: flash W */"]
                   if l in split else
                   [f"        sl_math_mvp_matrix_vector_mult_f16(&g_mat[{l}], g_in_f16[{l}], g_cur_f16[{l}]);"]),
                 *lap(f"affine{l}.mvp", "        "),
                 f"        for (int j = 0; j < {mlp.dims[l + 1]}; j++) {{ const float acc = (float)g_cur_f16[{l}][j] + mlp_layer{l}_bias[j]; g_act[{l}][j] = {relu(l)}; }}",
                 *lap(f"affine{l}.out", "        "),
                 "    }"]
        if folded:
            final_fn = ["static const float *mlp_final(const float *h)   /* folded output affine */", "{", *blk,
                        f"    return g_act[{l}];", "}", ""]
        else:
            body += blk
    body += [f"    return g_act[{n - 2 if fold_output_affine else n - 1}];", "}", ""]
    body += final_fn
    body = [b for b in body if b != ""] + [""]

    init = ["void snn_init(void)", "{", "    for (int l = 0; l < ISCAS_NUM_LAYERS; l++) {",
            "        const mlp_layer_t *L = &MLP_LAYERS[l];",
            "        g_act[l] = (float *)snn_alloc_check(malloc((size_t)L->out_features * sizeof(float)), \"g_act[l]\");",
            *([f"        if (l < {first_mvp}) {{ continue; }}   /* M33 layer: no FP16 copy, no MVP I/O */"] if first_mvp else []),
            "        const size_t n_weights = (size_t)L->out_features * (size_t)L->in_features;",
            *(_split_weight_init_lines() if split else []),
            *(_flash_weight_init_lines() if flash_w else [
            "        g_weight_f16[l] = (float16_t *)snn_alloc_check(malloc(n_weights * sizeof(float16_t)), \"g_weight_f16[l]\");",
            "        for (size_t idx = 0; idx < n_weights; idx++) { g_weight_f16[l][idx] = (float16_t)L->weight[idx]; }"]),
            "        sl_math_matrix_init_f16(&g_mat[l], L->out_features, L->in_features, g_weight_f16[l]);",
            "        g_in_f16[l] = (float16_t *)snn_alloc_check(malloc((size_t)L->in_features * sizeof(float16_t)), \"g_in_f16[l]\");",
            "        g_cur_f16[l] = (float16_t *)snn_alloc_check(malloc((size_t)L->out_features * sizeof(float16_t)), \"g_cur_f16[l]\");",
            "    }"]
    for l in sorted(static_io_layers):
        init.append(f"    g_in_f16[{l}] = g_io_in{l}; g_cur_f16[{l}] = g_io_cur{l};   /* static I/O */")
    if event_input_layer:
        init += cpu_sparse_init_lines(0, n0, event_weights)
    if reuse_empty_frames:
        init.append("    memcpy(g_empty_logits, mlp_final(mlp_eval(g_zero_frame, 0)), sizeof(g_empty_logits));   /* same code path, once */"
                    if fold_output_affine else
                    "    memcpy(g_empty_logits, mlp_eval(g_zero_frame, 0), sizeof(g_empty_logits));   /* same code path, once */")
    init += ["}", ""]

    counters = ["g_logit_sum"] + (["g_csp_event_count", "g_csp_empty_count", "g_csp_nonbinary_count"] if event_input_layer else []) \
        + (["g_csp_verify_mismatch"] if (event_input_layer or reuse_empty_frames) else [])
    rest = ["void iscas_infer_reset(const float *first_input)", "{", "    (void)first_input;",
            *[f"    memset({c}, 0, sizeof({c}));" for c in counters],
            *(["    g_mlp_reused_frames = 0;"] if reuse_empty_frames else []),
            *(["    memset(g_fold_hsum, 0, sizeof(g_fold_hsum));", "    g_fold_n = 0;", "    g_fold_empty = 0;"] if fold_output_affine else []),
            *(["#ifdef ISCAS_STAGE_PROFILE", "    memset(g_prof_cycles, 0, sizeof(g_prof_cycles));", "#endif"] if stage_profile else []),
            "}", "",
            "void iscas_infer_step(const float *step_input)", "{",
            *(["    ISCAS_PROF_START();"] if stage_profile else []),
            *([f"    const float *h = mlp_eval(step_input, {1 if reuse_empty_frames else 0});",
               "    if (h == 0) { g_fold_empty++; } else {   /* folded output affine: sum the penultimate activations */",
               f"        for (int i = 0; i < {mlp.dims[n - 1]}; i++) {{ g_fold_hsum[i] += h[i]; }}",
               "        g_fold_n++;", "    }", *lap("fold.acc", "    ")]
              if fold_output_affine else
              [f"    const float *lg = mlp_eval(step_input, {1 if reuse_empty_frames else 0});",
               f"    for (int j = 0; j < {out_dim}; j++) {{ g_logit_sum[j] += lg[j]; }}",
               *lap("logits", "    ")]),
            "}", "",
            "int iscas_infer_readout(void)", "{",
            *((["    ISCAS_PROF_START();"] if stage_profile else []) + [
               "    if (g_fold_n > 0) {   /* once: n_ne * (W mean(h) + b) */",
               "        const float inv = 1.0f / (float)g_fold_n;",
               f"        for (int i = 0; i < {mlp.dims[n - 1]}; i++) {{ g_fold_hsum[i] *= inv; }}",
               "        const float *lg = mlp_final(g_fold_hsum);",
               f"        for (int j = 0; j < {out_dim}; j++) {{ g_logit_sum[j] = (float)g_fold_n * lg[j]; }}",
               "    }",
               f"    for (int j = 0; j < {out_dim}; j++) {{ g_logit_sum[j] += (float)g_fold_empty * g_empty_logits[j]; }}",
               *lap("fold.final", "    ")] if fold_output_affine else []),
            "    int predicted_class = 0;", "    float best = g_logit_sum[0];",
            f"    for (int j = 1; j < {out_dim}; j++) {{", "        if (g_logit_sum[j] > best) { best = g_logit_sum[j]; predicted_class = j; }",
            "    }", "    return predicted_class;", "}", "",
            "int run_snn_inference(float *input_data)", "{", "    iscas_infer_reset(input_data);",
            f"    for (int t = 0; t < {num_steps}; t++) {{", "        iscas_infer_step(input_data + (size_t)t * ISCAS_INPUT_DIM);", "    }",
            "    return iscas_infer_readout();", "}", ""]
    if event_input_layer or reuse_empty_frames:
        rest += ["int iscas_debug_cpu_sparse_layer(int layer) { return layer == 0; }",
                 *(["int iscas_debug_cpu_sparse_event_count(int layer) { return g_csp_event_count[layer]; }",
                    "int iscas_debug_cpu_sparse_empty_count(int layer) { return g_csp_empty_count[layer]; }",
                    "int iscas_debug_cpu_sparse_nonbinary_count(int layer) { return g_csp_nonbinary_count[layer]; }"]
                   if event_input_layer else
                   ["int iscas_debug_cpu_sparse_event_count(int layer) { (void)layer; return -1; }",
                    "int iscas_debug_cpu_sparse_empty_count(int layer) { (void)layer; return g_mlp_reused_frames; }",
                    "int iscas_debug_cpu_sparse_nonbinary_count(int layer) { (void)layer; return -1; }"]),
                 "int iscas_debug_cpu_sparse_verify_mismatch(int layer) { return g_csp_verify_mismatch[layer]; }"]
    if reuse_empty_frames:
        rest.append("int iscas_debug_mlp_reused_frames(void) { return g_mlp_reused_frames; }")
    if stage_profile:
        assert len(names) <= 64
        rest += ["#ifdef ISCAS_STAGE_PROFILE",
                 f"static const char *const g_prof_names[{len(names)}] = {{{', '.join(repr(s).replace(chr(39), chr(34)) for s in names)}}};",
                 f"int iscas_debug_prof_count(void) {{ return {len(names)}; }}",
                 "const char *iscas_debug_prof_name(int s) { return g_prof_names[s]; }",
                 "unsigned long iscas_debug_prof_cycles(int s) { return (unsigned long)g_prof_cycles[s]; }",
                 "#endif"]
    return "\n".join(decl + [""] + body + init + rest) + "\n"


def _flash_weight_tables(mlp: MLPWeights, layers) -> List[str]:
    """Const flash tables with the FP16 weights of the listed layers (IEEE binary16 bits, equal to
    the ARM ``(float16_t)`` cast), read by the MVP in place."""
    import numpy as np
    out = ["#include <stdio.h>   /* W16FLASH check line (ISCAS_SPARSE_VERIFY builds) */"]
    for l in sorted(layers):
        bits = np.asarray(mlp.weights[l], dtype=np.float32).astype(np.float16).view(np.uint16)
        out.append(f"static const uint16_t mlp_w16_l{l}[{bits.size}] __attribute__((aligned(4))) = {{   /* flash-resident FP16 W */")
        out += ["    " + ", ".join(f"0x{v:04x}" for v in row) + "," for row in bits]
        out.append("};")
    out.append("static const uint16_t *const mlp_w16_flash[ISCAS_NUM_LAYERS] = {"
               + ", ".join(f"mlp_w16_l{l}" if l in layers else "0" for l in range(mlp.num_layers)) + "};")
    return out


def _split_weight_tables(mlp: MLPWeights, split) -> List[str]:
    """Flash FP16 tables of rows ``R..`` of each split layer, plus the second MVP matrix."""
    import numpy as np
    out = ["#include <stdio.h>   /* W16FLASH check line (ISCAS_SPARSE_VERIFY builds) */",
           "static sl_math_matrix_f16_t g_mat_tail[ISCAS_NUM_LAYERS];   /* rows R.. of a split layer: FP16 W in flash */"]
    for l, r_ in sorted(split.items()):
        bits = np.asarray(mlp.weights[l][r_:], dtype=np.float32).astype(np.float16).view(np.uint16)
        out.append(f"static const uint16_t mlp_w16_tail_l{l}[{bits.size}] __attribute__((aligned(4))) = {{   /* rows {r_}.. */")
        out += ["    " + ", ".join(f"0x{v:04x}" for v in row) + "," for row in bits]
        out.append("};")
    out.append("static const int mlp_split_rows[ISCAS_NUM_LAYERS] = {" + ", ".join(str(split.get(l, 0)) for l in range(mlp.num_layers)) + "};")
    out.append("static const uint16_t *const mlp_w16_tail[ISCAS_NUM_LAYERS] = {"
               + ", ".join(f"mlp_w16_tail_l{l}" if l in split else "0" for l in range(mlp.num_layers)) + "};")
    return out


